
CREATE TABLE public.origins (
  code INTEGER PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

GRANT SELECT ON public.origins TO authenticated;
GRANT ALL ON public.origins TO service_role;

ALTER TABLE public.origins ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Authenticated can read origins"
  ON public.origins FOR SELECT
  TO authenticated
  USING (true);

CREATE POLICY "Owners can manage origins"
  ON public.origins FOR ALL
  TO authenticated
  USING (public.has_role(auth.uid(), 'owner'::public.app_role))
  WITH CHECK (public.has_role(auth.uid(), 'owner'::public.app_role));

CREATE TRIGGER trg_origins_updated_at
  BEFORE UPDATE ON public.origins
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();


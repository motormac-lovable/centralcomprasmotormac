export function centroCustoKey(centro: CentroDeCusto): string {
  return `${centro.codigo} - ${centro.descricao}`;
}

export function isCentroCustoValido(codigo: unknown, descricao: unknown): boolean {
  return CENTROS_DE_CUSTO.some((c) => c.codigo === codigo && c.descricao === descricao);
}

export function centroCustoLabel(data: Record<string, unknown>): string {
  const codigo = data.centro_custo_codigo;
  const descricao = data.centro_custo_descricao;
  return typeof codigo === "string" && codigo && typeof descricao === "string" && descricao
    ? `${codigo} - ${descricao}`
    : "Não informado";
}
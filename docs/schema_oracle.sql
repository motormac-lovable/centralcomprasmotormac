-- ---------------------------------------------------------------------------
-- DOMÍNIOS (Oracle não possui ENUM: usar CHECK CONSTRAINT)
--   TIPO_SOLICITACAO : compras | contratos | frete | materiais
--   STATUS_CARD      : solicitacoes_abertas | em_cotacao | aguardando_aprovacao
--                      cotacoes_rejeitadas | cotacoes_aprovadas | pedidos_gerados
--   PERFIL_USUARIO   : owner | admin | buyer | aprovador | solicitante | auditor
-- ---------------------------------------------------------------------------

-- ============================ USUARIOS_PERFIS ==============================
CREATE TABLE USUARIOS_PERFIS (
  ID                   VARCHAR2(36)   NOT NULL,          -- UUID
  NOME_COMPLETO        VARCHAR2(200),
  EMAIL                VARCHAR2(200),
  CPF                  VARCHAR2(14),
  TELEFONE             VARCHAR2(20),
  ATIVO                NUMBER(1)      DEFAULT 1 NOT NULL,
  EXCLUIDO             NUMBER(1)      DEFAULT 0 NOT NULL,
  DATA_CRIACAO         TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  DATA_ATUALIZACAO     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_USUARIOS_PERFIS PRIMARY KEY (ID),
  CONSTRAINT UQ_USUARIOS_EMAIL  UNIQUE (EMAIL),
  CONSTRAINT CK_USUARIOS_ATIVO  CHECK (ATIVO IN (0,1))
);

CREATE TABLE USUARIOS_PAPEIS (
  ID          VARCHAR2(36) NOT NULL,
  ID_USUARIO  VARCHAR2(36) NOT NULL,
  PAPEL       VARCHAR2(20) NOT NULL,
  CONSTRAINT PK_USUARIOS_PAPEIS PRIMARY KEY (ID),
  CONSTRAINT UQ_USUARIO_PAPEL   UNIQUE (ID_USUARIO, PAPEL),
  CONSTRAINT FK_PAPEL_USUARIO   FOREIGN KEY (ID_USUARIO)
      REFERENCES USUARIOS_PERFIS (ID) ON DELETE CASCADE,
  CONSTRAINT CK_PAPEL_VALIDO CHECK (PAPEL IN
      ('owner','admin','buyer','aprovador','solicitante','auditor'))
);

-- Alçadas de aprovação (departamentos + teto financeiro)
CREATE TABLE APROVADORES_ALCADAS (
  ID_USUARIO       VARCHAR2(36) NOT NULL,
  DEPARTAMENTOS    VARCHAR2(4000) NOT NULL,   -- lista separada por ';'
  TETO_ALCADA      NUMBER(18,2) DEFAULT 0 NOT NULL,
  DATA_CRIACAO     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  DATA_ATUALIZACAO TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_APROV_ALCADAS PRIMARY KEY (ID_USUARIO),
  CONSTRAINT FK_ALCADA_USUARIO FOREIGN KEY (ID_USUARIO)
      REFERENCES USUARIOS_PERFIS (ID) ON DELETE CASCADE
);

-- ============================ TABELAS DE APOIO =============================
CREATE TABLE DEPARTAMENTOS (
  CODIGO NUMBER(6)      NOT NULL,
  NOME   VARCHAR2(200)  NOT NULL,
  CONSTRAINT PK_DEPARTAMENTOS PRIMARY KEY (CODIGO)
);

CREATE TABLE ORIGENS (
  CODIGO NUMBER(6)      NOT NULL,
  NOME   VARCHAR2(200)  NOT NULL,
  CONSTRAINT PK_ORIGENS PRIMARY KEY (CODIGO)
);

-- ============================== SOLICITACOES ===============================
CREATE TABLE SOLICITACOES (
  ID                   VARCHAR2(36)  NOT NULL,       -- UUID
  CODIGO_UNICO         VARCHAR2(30),                 -- MMYYYY + sequencial
  TIPO                 VARCHAR2(20)  NOT NULL,
  TITULO               VARCHAR2(400) NOT NULL,
  RESUMO               VARCHAR2(4000),
  STATUS               VARCHAR2(30)  DEFAULT 'solicitacoes_abertas' NOT NULL,
  ID_SOLICITANTE       VARCHAR2(36),
  NOME_SOLICITANTE     VARCHAR2(200),
  EMAIL_SOLICITANTE    VARCHAR2(200),
  UNIDADE              VARCHAR2(120),
  EMPRESA              VARCHAR2(120),
  DEPARTAMENTO         VARCHAR2(200),
  ORIGEM               VARCHAR2(200),
  NOME_COMPRADOR       VARCHAR2(200),
  DATA_VINCULO_COMPRADOR TIMESTAMP WITH TIME ZONE,
  ID_APROVADOR         VARCHAR2(36),
  NOME_APROVADOR       VARCHAR2(200),
  NUMERO_PEDIDO        VARCHAR2(60),
  NUMERO_PEDIDO_ERP    VARCHAR2(60),                 -- Linx Apollo
  DADOS_JSON           CLOB,                         -- payload do formulário
  FORNECEDORES_JSON    CLOB,                         -- cotações recebidas
  ANEXOS_JSON          CLOB,                         -- metadados de anexos
  DATA_CRIACAO         TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  DATA_ATUALIZACAO     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  DATA_MUDANCA_STATUS  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_SOLICITACOES        PRIMARY KEY (ID),
  CONSTRAINT UQ_SOLICITACOES_CODIGO UNIQUE (CODIGO_UNICO),
  CONSTRAINT FK_SOLIC_SOLICITANTE   FOREIGN KEY (ID_SOLICITANTE)
      REFERENCES USUARIOS_PERFIS (ID),
  CONSTRAINT FK_SOLIC_APROVADOR     FOREIGN KEY (ID_APROVADOR)
      REFERENCES USUARIOS_PERFIS (ID),
  CONSTRAINT CK_SOLIC_TIPO CHECK (TIPO IN ('compras','contratos','frete','materiais')),
  CONSTRAINT CK_SOLIC_STATUS CHECK (STATUS IN
      ('solicitacoes_abertas','em_cotacao','aguardando_aprovacao',
       'cotacoes_rejeitadas','cotacoes_aprovadas','pedidos_gerados')),
  CONSTRAINT CK_SOLIC_JSON CHECK (DADOS_JSON IS JSON)   -- Oracle 12c+
);

CREATE INDEX IX_SOLIC_STATUS      ON SOLICITACOES (STATUS);
CREATE INDEX IX_SOLIC_SOLICITANTE ON SOLICITACOES (ID_SOLICITANTE);
CREATE INDEX IX_SOLIC_CRIACAO     ON SOLICITACOES (DATA_CRIACAO);

-- Sequência do código único (MMYYYY + N)
CREATE SEQUENCE SEQ_SOLICITACAO START WITH 1 INCREMENT BY 1 NOCACHE;

-- ========================= MATERIAIS_SOLICITACAO ===========================
CREATE TABLE MATERIAIS_SOLICITACAO (
  ID               VARCHAR2(36)  NOT NULL,
  ID_SOLICITACAO   VARCHAR2(36)  NOT NULL,
  ORDEM            NUMBER(4)     DEFAULT 1 NOT NULL,
  CODIGO_MATERIAL  VARCHAR2(60),
  DESCRICAO        VARCHAR2(1000) NOT NULL,
  QUANTIDADE       NUMBER(18,4)   NOT NULL,
  UNIDADE_MEDIDA   VARCHAR2(20),
  DATA_CRIACAO     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_MATERIAIS_SOLIC PRIMARY KEY (ID),
  CONSTRAINT FK_MATERIAL_SOLIC  FOREIGN KEY (ID_SOLICITACAO)
      REFERENCES SOLICITACOES (ID) ON DELETE CASCADE
);
CREATE INDEX IX_MATERIAL_SOLIC ON MATERIAIS_SOLICITACAO (ID_SOLICITACAO);

-- ============================ HISTORICO_STATUS =============================
-- Trilha de auditoria em pt-BR (observações, movimentações, justificativas).
CREATE TABLE HISTORICO_STATUS (
  ID              VARCHAR2(36)   NOT NULL,
  ID_SOLICITACAO  VARCHAR2(36)   NOT NULL,
  STATUS_ANTERIOR VARCHAR2(30),
  STATUS_NOVO     VARCHAR2(30),
  AUTOR           VARCHAR2(200)  NOT NULL,
  ID_AUTOR        VARCHAR2(36),
  TEXTO           VARCHAR2(4000) NOT NULL,     -- log de auditoria em pt-BR
  DATA_EVENTO     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_HISTORICO_STATUS PRIMARY KEY (ID),
  CONSTRAINT FK_HIST_SOLIC FOREIGN KEY (ID_SOLICITACAO)
      REFERENCES SOLICITACOES (ID) ON DELETE CASCADE
);
CREATE INDEX IX_HIST_SOLIC ON HISTORICO_STATUS (ID_SOLICITACAO, DATA_EVENTO);

-- ================================ MENSAGENS ================================
CREATE TABLE MENSAGENS (
  ID              VARCHAR2(36)   NOT NULL,
  ID_SOLICITACAO  VARCHAR2(36)   NOT NULL,
  ID_REMETENTE    VARCHAR2(36)   NOT NULL,
  NOME_REMETENTE  VARCHAR2(200)  DEFAULT ' ' NOT NULL,
  EMAIL_REMETENTE VARCHAR2(200),
  TEL_REMETENTE   VARCHAR2(20),
  PAPEL_REMETENTE VARCHAR2(20)   DEFAULT 'solicitante' NOT NULL,
  NOME_COMPRADOR  VARCHAR2(200),
  CORPO           CLOB           NOT NULL,
  DATA_LEITURA    TIMESTAMP WITH TIME ZONE,
  DATA_CRIACAO    TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  DATA_ATUALIZACAO TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_MENSAGENS PRIMARY KEY (ID),
  CONSTRAINT FK_MSG_SOLIC     FOREIGN KEY (ID_SOLICITACAO)
      REFERENCES SOLICITACOES (ID) ON DELETE CASCADE,
  CONSTRAINT FK_MSG_REMETENTE FOREIGN KEY (ID_REMETENTE)
      REFERENCES USUARIOS_PERFIS (ID)
);
CREATE INDEX IX_MSG_SOLIC   ON MENSAGENS (ID_SOLICITACAO, DATA_CRIACAO);
CREATE INDEX IX_MSG_NAOLIDA ON MENSAGENS (DATA_LEITURA);

-- ============================ DOCUMENTOS/ANEXOS ============================
CREATE TABLE DOCUMENTOS_SOLICITACAO (
  ID              VARCHAR2(36)  NOT NULL,
  ID_SOLICITACAO  VARCHAR2(36)  NOT NULL,
  CATEGORIA       VARCHAR2(30)  NOT NULL,   -- solicitante | orcamento | nf | boleto | xml
  NOME_ARQUIVO    VARCHAR2(400) NOT NULL,
  CAMINHO         VARCHAR2(1000) NOT NULL,  -- caminho no storage corporativo
  TAMANHO_BYTES   NUMBER(18),
  TIPO_MIME       VARCHAR2(120),
  ID_ENVIADO_POR  VARCHAR2(36),
  DATA_UPLOAD     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_DOCS_SOLIC PRIMARY KEY (ID),
  CONSTRAINT FK_DOC_SOLIC  FOREIGN KEY (ID_SOLICITACAO)
      REFERENCES SOLICITACOES (ID) ON DELETE CASCADE
);
CREATE INDEX IX_DOC_SOLIC ON DOCUMENTOS_SOLICITACAO (ID_SOLICITACAO, CATEGORIA);

-- ============================ NOTAS DE PORTABILIDADE =======================
-- SQL Server : VARCHAR2→NVARCHAR, NUMBER(1)→BIT, CLOB→NVARCHAR(MAX),
--              TIMESTAMP WITH TIME ZONE→DATETIMEOFFSET, SEQUENCE nativa.
-- PostgreSQL : VARCHAR2→VARCHAR/UUID, CLOB→JSONB, NUMBER(1)→BOOLEAN,
--              TIMESTAMP WITH TIME ZONE→TIMESTAMPTZ, CHECK→ENUM nativo.
